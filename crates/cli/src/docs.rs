//! Generated documentation. `docs/ops.md` comes only from the op table in
//! `rulelab-vm`, so the two can never disagree.

use rulelab_vm::ops;

/// Renders the register map and op table as `docs/ops.md`.
pub fn ops_markdown() -> String {
    let mut s = String::from(
        "# Rule VM: registers and ops\n\n\
         Generated by `rulelab docs` from `crates/vm/src/ops.rs`. Do not edit by hand.\n\n\
         A learn program is 0 to 8 instructions of 16 bits, `op[15:12] dst[11:8] a[7:4] b[3:0]`, \
         run once per synapse per step. `dst` must be r12 to r15; any other value is an error. \
         Unary ops are written `op dst a`; the rest `op dst a b`.\n\n\
         ## Registers\n\n| Reg | Name | Meaning | Initial value |\n| --- | --- | --- | --- |\n",
    );
    for (i, r) in ops::REGS.iter().enumerate() {
        s += &format!("| r{i} | `{}` | {} | {} |\n", r.name, r.meaning, r.init);
    }
    s += "\nAn empty program is the identity: `dw` = 0 and the trace is kept.\n\n\
          ## Ops\n\n| Code | Op | Form | Semantics |\n| --- | --- | --- | --- |\n";
    for o in &ops::OPS {
        let form = if o.uses_b { "op d a b" } else { "op d a" };
        s += &format!("| {:x} | `{}` | `{form}` | {} |\n", o.code, o.name, o.semantics);
    }
    s += "\n## Rule numbers\n\n\
          A program is canonicalized before numbering: dead instructions are dropped, unused `b` \
          fields are zeroed, and the operands of commutative ops (`add`, `mul`, `min`, `max`) are \
          sorted. The number is `R<length>-<hex words>` joined by `.`, for example `R1-3c01` \
          (`mul dw pre post`, Hebbian). The empty rule is `R0`.\n";
    s
}

#[cfg(test)]
mod tests {
    #[test]
    fn ops_doc_is_up_to_date() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/ops.md");
        let on_disk = std::fs::read_to_string(path).expect("docs/ops.md missing; run `rulelab docs`");
        assert!(on_disk == super::ops_markdown(), "docs/ops.md is stale; run `rulelab docs`");
    }
}
